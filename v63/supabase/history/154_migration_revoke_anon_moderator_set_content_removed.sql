-- 154_migration_revoke_anon_moderator_set_content_removed.sql
--
-- Closes a stray EXECUTE grant on moderator_set_content_removed() (150_migration_moderation_
-- removal_audit_log.sql): the function has always independently required is_moderator (auth.uid()
-- resolves to null for an unauthenticated caller, so the check fails before any table branch
-- runs), so this was never exploitable — but the grant itself shouldn't have existed. Confirmed
-- via a read-only audit (2026-09-26) that:
--   1. No migration ever explicitly granted anon EXECUTE on this function — 150 and 153 both only
--      wrote `revoke all ... from public; grant execute ... to authenticated;`.
--   2. Supabase's project-wide default privileges auto-grant EXECUTE to anon/authenticated on any
--      new public-schema function, before a migration's own revoke/grant lines run — the same
--      mechanism already documented and fixed for a different function in migration 143
--      ("Supabase default privileges had granted it to anon/authenticated") and again for
--      create_manual_withdrawal_locked() ("Also drop the anon/authenticated grants Supabase's
--      default privileges add to new functions"). `revoke all ... from public` does not touch
--      that separate, directly-granted anon privilege, so it survived both 150's own creation and
--      153's later CREATE OR REPLACE (which never touches existing grants at all).
--   3. The only call site in the app (setContentRemoved() in src/lib/moderation.js) is reachable
--      solely through the moderator-gated ModerationQueue screen, which requires a real signed-in
--      moderator session — no anonymous or public-facing path calls this RPC.
--
-- Minimal and scoped: revokes only anon's EXECUTE on this one function. authenticated's EXECUTE
-- (granted explicitly by 150 and re-affirmed by 153) is untouched, as is the function body, its
-- RLS-adjacent trigger interactions, and every other privilege on every other object.
--
-- Do not edit this file in place once it has run anywhere — redefine via a new migration, exactly
-- as every other migration in this repo does.

revoke execute on function moderator_set_content_removed(text, text, boolean, text) from anon;
